import Link from "next/link";
import { ArrowRight, Download, Eye, Search } from "lucide-react";
import { requireUser } from "@/lib/auth";
import { prisma } from "@/lib/prisma";
import { currentMonth, monthLabel, validMonth } from "@/lib/monthly-progress";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";

export const dynamic = "force-dynamic";

// Display the designated template preparer without changing audit actors or saved authors.
function generatorName(report?: { authorName: string }) {
  return !report || report.authorName === "Not documented" ? "Fikiraddis Worku" : report.authorName;
}

export default async function MonthlyProgressPage({ searchParams }: { searchParams: Promise<Record<string, string | string[] | undefined>> }) {
  await requireUser();
  const params = await searchParams;
  const month = typeof params.month === "string" && validMonth(params.month) ? params.month : currentMonth();
  const query = typeof params.q === "string" ? params.q.trim().slice(0, 100) : "";
  const clients = await prisma.client.findMany({ orderBy: { name: "asc" }, select: { id: true, name: true, monthlyReports: { where: { month }, select: { id: true, authorName: true } } } });
  const saved = clients.filter((client) => client.monthlyReports.length > 0).length;
  const visible = clients.filter((client) => !query || client.name.toLowerCase().includes(query.toLowerCase()));
  const packet = "/api/reports/monthly?month=" + month;
  return <section className="space-y-6">
    <div className="flex flex-wrap items-center justify-between gap-3">
      <div><h1 className="text-2xl font-semibold">Monthly Resident Progress</h1><p className="mt-1 text-sm text-muted-foreground">{monthLabel(month)}</p></div>
      {saved > 0 && <div className="flex flex-wrap gap-2"><Button asChild variant="secondary"><Link href={packet + "&preview=1"} target="_blank" rel="noopener noreferrer" prefetch={false}><Eye className="h-4 w-4" />Preview packet</Link></Button><Button asChild><Link href={packet} prefetch={false}><Download className="h-4 w-4" />Download packet ({saved})</Link></Button></div>}
    </div>
    <form action="/monthly" className="grid items-end gap-4 sm:grid-cols-2 lg:grid-cols-[1fr_2fr_auto]">
      <div><Label htmlFor="monthly-month">Reporting month</Label><Input id="monthly-month" name="month" type="month" defaultValue={month} required /></div>
      <div><Label htmlFor="monthly-search">Resident</Label><Input id="monthly-search" name="q" defaultValue={query} placeholder="Search residents" /></div>
      <Button type="submit"><Search className="h-4 w-4" />Filter</Button>
    </form>
    <div className="divide-y border-y md:hidden">{visible.map((client) => <div key={client.id} className="flex items-center justify-between gap-3 py-4">
      <div className="min-w-0"><h2 className="break-words font-semibold">{client.name}</h2><p className="mt-1 break-words text-xs text-muted-foreground">Generated by: {generatorName(client.monthlyReports[0])}</p></div>
      <Button asChild size="sm" variant="secondary"><Link aria-label={"Edit report for " + client.name} href={"/monthly/" + client.id + "?month=" + month}>Edit report<ArrowRight className="h-4 w-4" /></Link></Button>
    </div>)}{!visible.length && <p className="py-6 text-sm text-muted-foreground">No residents match these filters.</p>}</div>
    <div className="hidden overflow-x-auto md:block"><table className="w-full text-left text-sm">
      <thead className="bg-muted"><tr>{["Resident", "Generated by", "Report"].map((label) => <th key={label} scope="col" className="p-3">{label}</th>)}</tr></thead>
      <tbody>{visible.map((client) => <tr key={client.id} className="border-b">
        <td className="p-3 font-medium">{client.name}</td><td className="p-3">{generatorName(client.monthlyReports[0])}</td>
        <td className="p-3"><Link aria-label={"Edit report for " + client.name} className="inline-flex items-center gap-1 font-medium text-primary underline" href={"/monthly/" + client.id + "?month=" + month}>Edit report<ArrowRight className="h-4 w-4" /></Link></td>
      </tr>)}{!visible.length && <tr><td colSpan={3} className="p-8 text-center text-muted-foreground">No residents match these filters.</td></tr>}</tbody>
    </table></div>
  </section>;
}
